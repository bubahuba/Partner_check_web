export function getSiteUrl() {
  return (process.env.NEXT_PUBLIC_SITE_URL || '').replace(/\/$/, '')
}

export function getOgImageUrl() {
  const base = getSiteUrl()
  return base ? `${base}${OG_IMAGE_PATH}` : OG_IMAGE_PATH
}

export function getPageUrl(locale, path = '/') {
  const base = getSiteUrl()
  let pathname
  if (!locale) {
    pathname = path === '/' ? '/' : path.startsWith('/') ? path : `/${path}`
    if (pathname !== '/' && !pathname.endsWith('/')) pathname += '/'
  } else if (path === '/') {
    pathname = `/${locale}/`
  } else {
    const segment = path.startsWith('/') ? path : `/${path}`
    pathname = `/${locale}${segment}${segment.endsWith('/') ? '' : '/'}`
  }
  return base ? `${base}${pathname}` : pathname
}

export function getOgLocale(locale) {
  if (!locale) return null
  return ogLocaleMap[locale] || ogLocaleMap.en
}
