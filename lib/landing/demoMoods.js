export function getMoodWords(locale) {
  return demoMoodWords[locale] || demoMoodWords.en
}

/** @deprecated use getMoodWords */
export function getMoodPool(locale) {
  return getMoodWords(locale)
}

function shuffle(items) {
  const copy = [...items]
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

export function formatMoodPair(wordA, wordB) {
  return `${wordA} · ${wordB}`
}

function pickRandomMoodPair(locale) {
  const [a, b] = shuffle(getMoodWords(locale))
  return formatMoodPair(a, b)
}

export function pickRandomMoods(locale, count = 3) {
  return Array.from({ length: count }, () => pickRandomMoodPair(locale))
}

export function getStaticMoods(locale, count = 3) {
  const words = getMoodWords(locale)
  return Array.from({ length: count }, (_, i) => {
    const a = words[(i * 2) % words.length]
    const b = words[(i * 2 + 1) % words.length]
    return formatMoodPair(a, b)
  })
}
